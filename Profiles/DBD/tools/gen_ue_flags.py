"""Regenerates ue_flags.py from the stock 5.7.4 headers (read only). Usage: python -I gen_ue_flags.py <engine_root>"""
import re, sys, os
root = sys.argv[1] if len(sys.argv) > 1 else r'C:\Workspace\UnrealEngine-5.7.4-release'
U = os.path.join(root, 'Engine', 'Source', 'Runtime', 'CoreUObject', 'Public', 'UObject')
def grab(path, prefix):
    out = {}
    for l in open(os.path.join(U, path), encoding='utf8', errors='ignore'):
        m = re.match(r'\s*(%s\w+)\s*=\s*(0x[0-9A-Fa-f]+)[uU]?L*,' % prefix, l)
        if m: out[m.group(1)] = int(m.group(2), 16)
    return out
T = {'CPF': grab('ObjectMacros.h', 'CPF_'), 'CLASS': grab('ObjectMacros.h', 'CLASS_'),
     'FUNC': grab('Script.h', 'FUNC_'), 'STRUCT': grab('Class.h', 'STRUCT_')}
T['CLASS']['CLASS_Parsed'] = 0x100  # unused bit named Parsed by the jmap tool
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ue_flags.py'), 'w') as f:
    f.write('# Generated by gen_ue_flags.py from UE 5.7.4 headers. Do not edit.\n')
    for k, d in T.items():
        f.write('%s = {\n' % k)
        for n, v in sorted(d.items(), key=lambda x: (x[1], x[0])): f.write("    '%s': 0x%X,\n" % (n, v))
        f.write('}\n')
print({k: len(v) for k, v in T.items()})
